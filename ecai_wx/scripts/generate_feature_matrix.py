def merge_consecutive(ws, column, start_row, end_row):
    group_start = start_row
    current = ws.cell(start_row, column).value
    for row in range(start_row + 1, end_row + 2):
        value = ws.cell(row, column).value if row <= end_row else object()
        if value != current:
            if row - group_start > 1:
                ws.merge_cells(start_row=group_start, start_column=column, end_row=row - 1, end_column=column)
            group_start = row
            current = value


